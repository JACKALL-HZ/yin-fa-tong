GREEN_MESSAGE = "症状暂无明显急危重信号，建议按推荐科室正常预约就诊。"


def triage_by_rule(symptom_text: str) -> tuple[str, str]:
    """规则词库判定紧急级别（无 LLM 依赖）

    Returns:
        (level, message): level ∈ {"red","yellow","green"}
    """
    text = symptom_text.lower()

    # RED 优先
    for rule in EMERGENCY_RED:
        for kw in rule["keywords"]:
            if kw.lower() in text:
                return "red", rule["message"]

    # YELLOW 次之
    for rule in EMERGENCY_YELLOW:
        for kw in rule["keywords"]:
            if kw.lower() in text:
                return "yellow", rule["message"]

    return "green", GREEN_MESSAGE
